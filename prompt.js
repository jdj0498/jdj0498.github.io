function rand(n) {
  return globalThis.crypto.getRandomValues(new Uint32Array(1))[0] % n;
}
function weighted(list) {
  const total = list.reduce((a, [, w]) => a + w, 0);
  let r = rand(total);
  for (const [v, w] of list) { if ((r -= w) < 0) return v; }
  return list[0][0];
}

// 게임 날짜 문자열에서 미래 모드 여부를 추정: true / false / null(모름)
export function isFutureDate(dateText, now = new Date()) {
  const t = String(dateText || "");
  if (!t || /기원전|BC|B\.C/i.test(t)) return t ? false : null;
  const y = t.match(/(\d{3,5})\s*년/);
  if (!y) return null;
  const year = Number(y[1]);
  if (year !== now.getFullYear()) return year > now.getFullYear();
  const m = t.match(/년\s*(\d{1,2})\s*월/);
  return m ? Number(m[1]) > now.getMonth() + 1 : false;
}

